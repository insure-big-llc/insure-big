/**
 * Post-build path fixes. Runs automatically after `astro build`.
 *
 * ── Why this exists ──────────────────────────────────────────────────────────
 * /terms-%26-conditions is an indexed URL (website-scope.md §4). The percent-
 * encoded ampersand is real and must be preserved — /terms-conditions would be a
 * different URL, and Google currently has the encoded one.
 *
 * Astro URL-decodes route filenames before reading them, which rules out naming
 * the source file `terms-%26-conditions.astro`. The workaround is a bracketed
 * dynamic segment (`terms-[amp]conditions.astro`) that resolves to `%26` — which
 * produces the CORRECT canonical but emits the file as:
 *
 *     dist/terms-%26conditions.html     ← hyphen lost
 *
 * A static host maps a file named `terms-%26conditions.html` to both
 * /terms-%26conditions and (via the redirect rule) /terms-%26-conditions, so the
 * right URL happens to work — but a file whose name matches the canonical exactly
 * is unambiguous and does not depend on redirect behaviour. So we rename it.
 *
 * This is the ONLY post-processing the build needs; everything else is emitted
 * correctly by Astro.
 */
import { existsSync, renameSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const DIST = new URL('../dist/', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');

/** [generatedByAstro, canonicalFilename] */
const RENAMES = [['terms-%26conditions.html', 'terms-%26-conditions.html']];

let changed = 0;
for (const [from, to] of RENAMES) {
  const src = join(DIST, from);
  const dst = join(DIST, to);
  if (!existsSync(src)) {
    // Already named correctly (e.g. an Astro upgrade fixes the decoding): no-op.
    if (existsSync(dst)) continue;
    console.warn(`postbuild: expected ${from} but found neither it nor ${to}`);
    continue;
  }
  renameSync(src, dst);
  console.log(`postbuild: ${from} -> ${to}`);
  changed++;
}

if (changed === 0) console.log('postbuild: no path fixes needed');

/**
 * ── Partner outbound redirects ──────────────────────────────────────────────
 *
 * Every partner link on the site points at /go/<slug> rather than the partner's
 * URL directly. That buys three things:
 *
 *   1. outbound clicks are countable at the server, so we can see which cover
 *      lines actually get clicked before anyone leaves for a partner
 *   2. a partner URL changes in src/config/partners.js alone — no page edits
 *   3. the destination is never hardcoded in a template
 *
 * A static site cannot issue a real 302, so these are emitted as Netlify
 * `_redirects` rules, which Netlify serves as genuine 302s. That is better than a
 * client-side meta-refresh stub: no flash of an intermediate page, and crawlers
 * follow a real HTTP redirect.
 *
 * ⚠️ 302 not 301 on purpose. A 301 would tell Google to treat the partner's site
 * as the permanent replacement for that path, transferring any accumulated
 * authority off-domain. 302 keeps it here.
 */
const partnersConfig = readFileSync(
  new URL('../src/config/partners.js', import.meta.url),
  'utf8',
);

/**
 * Parse the partner registry without importing it — the module is ESM with
 * comments and would need a loader. The shape is deliberately simple: one
 * `slug: { ... url: '...', shipsLink: bool }` block per partner.
 */
const REDIRECTS_MARKER = '# ── Partner outbound redirects (generated) ─────';
const redirectRules = [];

const blockRe = /^\s{2}(?:'([^']+)'|([a-z-]+)):\s*\{([\s\S]*?)^\s{2}\},/gm;
for (const m of partnersConfig.matchAll(blockRe)) {
  const slug = m[1] ?? m[2];
  const body = m[3];
  const urlMatch = body.match(/^\s*url:\s*(?:'([^']*)'|"([^"]*)"|null)/m);
  const url = urlMatch ? (urlMatch[1] ?? urlMatch[2] ?? null) : null;
  const shipsLink = /shipsLink:\s*true/.test(body);

  // Only emit a redirect when a link is actually rendered. Medicare has
  // shipsLink: false and url: null precisely so that NO redirect exists for it.
  if (shipsLink && url) {
    redirectRules.push(`/go/${slug}    ${url}    302`);
  }
}

const redirectsPath = join(DIST, '_redirects');
if (!existsSync(redirectsPath)) {
  console.warn('postbuild: dist/_redirects missing — partner redirects not written');
} else if (redirectRules.length === 0) {
  console.warn('postbuild: no partner redirects generated — check partners.js parsing');
} else {
  let body = readFileSync(redirectsPath, 'utf8');

  // Idempotent: drop any previously generated block so repeat builds do not stack.
  const idx = body.indexOf(REDIRECTS_MARKER);
  if (idx !== -1) body = body.slice(0, idx).trimEnd() + '\n';

  const block = [
    '',
    REDIRECTS_MARKER,
    '# Generated by scripts/postbuild.mjs from src/config/partners.js.',
    '# 302, never 301 — a permanent redirect would hand the partner the authority',
    '# for this path, which is the exact leak this site is trying to stop.',
    '# Medicare is deliberately absent: its link is withheld until the',
    '# arrangement is confirmed.',
    '',
    ...redirectRules,
    '',
  ].join('\n');

  writeFileSync(redirectsPath, body + block, 'utf8');
  console.log(`postbuild: wrote ${redirectRules.length} partner redirect(s) to _redirects`);
}

/**
 * Font wiring, generated from what is actually on disk.
 *
 * WHY THIS IS GENERATED
 * ---------------------
 * The brand fonts (Poppins for body, Cantarell for headings) must be SELF-HOSTED.
 * Loading them from Google's CDN would add a render-blocking third-party request
 * and leak visitor IPs — both of which the scope rules out.
 *
 * This script runs before the build and:
 *   1. copies the latin-subset .woff2 files from the installed @fontsource
 *      packages (node_modules) into public/fonts/ — unless a file already exists
 *      there, in which case the manual file wins
 *   2. emits public/fonts.css declaring @font-face ONLY for files present
 *   3. writes src/generated/fonts.js listing them, so the layout can preload
 *      exactly the fonts that exist and nothing else
 *
 * A missing file therefore degrades to the system stack rather than producing a
 * 404 or a wasted preload. If @fontsource is ever removed from package.json, the
 * manual drop-in route below keeps working unchanged.
 *
 * SOURCE MAPPING (latin subset only — the site is English):
 *   poppins-latin-400-normal.woff2  -> poppins-400.woff2
 *   poppins-latin-600-normal.woff2  -> poppins-600.woff2
 *   poppins-latin-700-normal.woff2  -> poppins-700.woff2
 *   cantarell-latin-400-normal.woff2 -> cantarell-400.woff2
 *   cantarell-latin-700-normal.woff2 -> cantarell-700.woff2
 */
import { existsSync, mkdirSync, writeFileSync, readdirSync, copyFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('../', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const PUBLIC = join(ROOT, 'public');
const FONT_DIR = join(PUBLIC, 'fonts');
const GENERATED = join(ROOT, 'src', 'generated');
const NODE_MODULES = join(ROOT, 'node_modules', '@fontsource');

/**
 * font-family -> [{ file (public name), weight, style, source (in the
 * @fontsource files dir) }]
 */
const EXPECTED = {
  Poppins: [
    { file: 'poppins-400.woff2', weight: 400, style: 'normal', source: 'poppins-latin-400-normal.woff2' },
    { file: 'poppins-600.woff2', weight: 600, style: 'normal', source: 'poppins-latin-600-normal.woff2' },
    { file: 'poppins-700.woff2', weight: 700, style: 'normal', source: 'poppins-latin-700-normal.woff2' },
  ],
  Cantarell: [
    { file: 'cantarell-400.woff2', weight: 400, style: 'normal', source: 'cantarell-latin-400-normal.woff2' },
    { file: 'cantarell-700.woff2', weight: 700, style: 'normal', source: 'cantarell-latin-700-normal.woff2' },
  ],
};

mkdirSync(FONT_DIR, { recursive: true });
mkdirSync(GENERATED, { recursive: true });

// ── Step 1: copy latin subsets from the installed @fontsource packages ──────
// Only where the destination file does not already exist — a manually dropped
// file always wins, so the copy step is idempotent and non-destructive.
let copied = 0;
let copyMissing = 0;
for (const [family, faces] of Object.entries(EXPECTED)) {
  const pkgFiles = join(NODE_MODULES, family.toLowerCase(), 'files');
  for (const face of faces) {
    const dst = join(FONT_DIR, face.file);
    if (existsSync(dst)) continue;
    const src = join(pkgFiles, face.source);
    if (existsSync(src)) {
      copyFileSync(src, dst);
      copied++;
    } else {
      copyMissing++;
      console.warn(`fonts: @fontsource/${family} is missing ${face.source} — manual drop-in required`);
    }
  }
}

// ── Step 2: scan what is now on disk ─────────────────────────────────────────
const onDisk = new Set(existsSync(FONT_DIR) ? readdirSync(FONT_DIR) : []);

const css = [
  '/* GENERATED by scripts/build-fonts.mjs — do not edit by hand. */',
  '/* Self-hosted brand fonts. Only faces whose .woff2 exists are declared. */',
  '',
];
const present = [];
const missing = [];

for (const [family, faces] of Object.entries(EXPECTED)) {
  for (const face of faces) {
    if (!onDisk.has(face.file)) {
      missing.push(`${family} ${face.weight}`);
      continue;
    }
    present.push({ family, ...face, href: `/fonts/${face.file}` });
    css.push(
      '@font-face {',
      `  font-family: '${family}';`,
      `  font-style: ${face.style};`,
      `  font-weight: ${face.weight};`,
      '  font-display: swap;',
      `  src: url('/fonts/${face.file}') format('woff2');`,
      '}',
      '',
    );
  }
}

writeFileSync(join(PUBLIC, 'fonts.css'), css.join('\n'), 'utf8');

const js = `/**
 * GENERATED by scripts/build-fonts.mjs — do not edit by hand.
 *
 * Fonts whose .woff2 is present in public/fonts at build time. The layout
 * preloads exactly these, so we never emit a preload for a missing file.
 */
export const SELF_HOSTED_FONTS = ${JSON.stringify(present, null, 2)};

/** Faces the brand calls for that are not yet on disk. Drives the build warning. */
export const MISSING_FONT_FACES = ${JSON.stringify(missing, null, 2)};

export const FONTS_READY = MISSING_FONT_FACES.length === 0;
`;
writeFileSync(join(GENERATED, 'fonts.js'), js, 'utf8');

console.log(
  `fonts: copied ${copied} from @fontsource, ${present.length} face(s) declared, ${missing.length} missing`,
);
if (copyMissing > 0) {
  console.log(
    `fonts: ${copyMissing} face(s) could not be copied from @fontsource — check package.json`,
  );
}
if (missing.length) {
  console.log(
    `fonts: still to supply -> ${missing.join(', ')}\n` +
      `       put .woff2 files in public/fonts/ and rebuild; no source change needed`,
  );
}
